path = kagglehub.dataset_download("desolution01/messy-employee-dataset")

print("Path to dataset files:", path)

import numpy as np
import pandas as pd

df = pd.read_csv("/kaggle/input/messy-employee-dataset/Messy_Employee_dataset.csv")
df.head(3)

# standardize columns
# df.columns = ('emp_id', 'fname', 'lname'...)
df.columns = [x.lower() for x in df.columns]
df.columns

df.describe()

df.dtypes

df.duplicated().sum()

df.drop_duplicates() # remove duplicate rows

df.isna().sum()

df['age'].fillna(df['age'].mean(), inplace=True)
df['salary'].fillna(0, inplace=True)

df['email'].duplicated().sum()
df.drop_duplicates(subset=['email'], inplace=True)

df.shape

def updatePhone(num):
  return abs(num)

df['phone'] = df['phone'].apply(updatePhone)

from sklearn.preprocessing import LabelEncoder

encoder = LabelEncoder()

df['status'] = encoder.fit_transform(df['status'])

df['performance_score'] = encoder.fit_transform(df['performance_score'])
df['remote_work'] = encoder.fit_transform(df['remote_work'])

